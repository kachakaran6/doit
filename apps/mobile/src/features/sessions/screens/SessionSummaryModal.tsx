import React from 'react';
import { View, StyleSheet, ScrollView, Share } from 'react-native';
import { useTheme } from '../../../theme/useTheme';
import { Sheet, Text, Button } from '../../../components/ui';
import { useSessionStore } from '../store';
import { CheckCircle2, Share2, ListPlus } from 'lucide-react-native';

export interface SessionSummaryModalProps {
  visible: boolean;
  onClose: () => void;
}

export const SessionSummaryModal: React.FC<SessionSummaryModalProps> = ({ visible, onClose }) => {
  const { colors, spacing, radius } = useTheme();
  const { appUnderTest, bugIds, elapsedSeconds, endSession } = useSessionStore();

  const handleShareReport = async () => {
    const reportMarkdown = [
      `# Test Session Report: ${appUnderTest}`,
      `- **Duration:** ${Math.floor(elapsedSeconds / 60)}m ${elapsedSeconds % 60}s`,
      `- **Total Bugs Reported:** ${bugIds.length}`,
      `- **Captured At:** ${new Date().toISOString()}`,
      '',
      'Generated by Samyukt Doit QA System',
    ].join('\n');

    await Share.share({
      message: reportMarkdown,
      title: `Test Session Report - ${appUnderTest}`,
    });
  };

  const handleFinish = () => {
    endSession();
    onClose();
  };

  return (
    <Sheet visible={visible} onClose={handleFinish} detent={0.9} title="Session Completed">
      <ScrollView contentContainerStyle={{ padding: spacing.lg, gap: spacing.lg }}>
        <View style={styles.header}>
          <CheckCircle2 size={36} color={colors.success} />
          <Text variant="h2" style={{ marginTop: spacing.sm }}>
            Test Run Finished
          </Text>
          <Text variant="caption" color="secondary">
            Testing target: {appUnderTest}
          </Text>
        </View>

        {/* Metrics Grid */}
        <View
          style={[
            styles.metricsBox,
            {
              backgroundColor: colors.surface,
              borderColor: colors.border,
              borderRadius: radius.md,
              padding: spacing.lg,
            },
          ]}
        >
          <View style={styles.metric}>
            <Text variant="caption" color="secondary">
              Duration
            </Text>
            <Text variant="h3">
              {Math.floor(elapsedSeconds / 60)}m {elapsedSeconds % 60}s
            </Text>
          </View>

          <View style={styles.metric}>
            <Text variant="caption" color="secondary">
              Bugs Created
            </Text>
            <Text variant="h3">{bugIds.length}</Text>
          </View>
        </View>

        {/* Action Buttons */}
        <View style={{ gap: spacing.sm }}>
          <Button
            title="Share Report (Markdown)"
            variant="primary"
            icon={<Share2 size={16} color={colors.accentOnPrimary} />}
            onPress={handleShareReport}
          />

          <Button
            title="Create Tasks from All"
            variant="secondary"
            icon={<ListPlus size={16} color={colors.textPrimary} />}
            onPress={handleFinish}
          />

          <Button
            title="Done"
            variant="ghost"
            onPress={handleFinish}
          />
        </View>
      </ScrollView>
    </Sheet>
  );
};

const styles = StyleSheet.create({
  header: {
    alignItems: 'center',
    justifyContent: 'center',
  },
  metricsBox: {
    flexDirection: 'row',
    justifyContent: 'space-around',
    borderWidth: 1,
  },
  metric: {
    alignItems: 'center',
  },
});
